"""bots_common/site_logins.py: a stored login, as one yt-dlp run sees it.

The private-copy, write-back and fallback paths are exercised end to end
through the Discord bot in test_discord_routing.py; what is left here is
the helper's own edges.
"""
import asyncio
import os

import pytest

from bots_common import site_logins
from bots_common.resolver import ResolveError

COOKIES = '.youtube.com\tTRUE\t/\tTRUE\t0\tSAPISID\tx\n'


def run(coro):
    return asyncio.run(coro)


class FakeIndex:
    def __init__(self, login=None):
        self.login = login
        self.stored = []

    async def site_login(self, url):
        return self.login

    async def store_site_login(self, login, text):
        self.stored.append(text)
        return 1


def _login(text=COOKIES):
    return site_logins.StoredLogin('youtube', 'YouTube', 3, text)


def test_the_copy_is_removed_even_when_the_run_blows_up(tmp_path):
    index = FakeIndex(_login())
    seen = {}

    async def go():
        async with site_logins.cookies_for(index, 'u', str(tmp_path)) as run_:
            seen['path'] = run_.path
            run_.used = True
            raise RuntimeError("resolve exploded")

    with pytest.raises(RuntimeError):
        run(go())
    assert not os.path.exists(seen['path'])
    assert index.stored == [], "a failed run's jar is never sent back"


def test_the_copy_is_named_for_the_resolvers_sweep(tmp_path):
    """A resolve that hangs past its ceiling leaves a thread that saves the
    jar again later; the resolver's own sweep must be able to reclaim it."""
    async def go():
        async with site_logins.cookies_for(FakeIndex(_login()), 'u',
                                           str(tmp_path)) as run_:
            return os.path.basename(run_.path)
    assert run(go()).startswith('ytdlp-')


def test_reordered_and_recommented_cookies_are_not_a_rotation(tmp_path):
    """yt-dlp rewrites the file with its own header even when nothing
    changed; that is not worth a write."""
    index = FakeIndex(_login('# Netscape HTTP Cookie File\n' + COOKIES))

    async def go():
        async with site_logins.cookies_for(index, 'u', str(tmp_path)) as run_:
            with open(run_.path, 'w') as fh:
                fh.write('# Netscape HTTP Cookie File\n'
                         '# This file is generated by yt-dlp.\n\n' + COOKIES)
            run_.used = True

    run(go())
    assert index.stored == []


def test_no_stored_login_and_no_fallback_means_no_cookies(tmp_path):
    async def go():
        async with site_logins.cookies_for(FakeIndex(), 'u',
                                           str(tmp_path)) as run_:
            return run_.path, run_.login
    assert run(go()) == (None, None)


@pytest.mark.parametrize('data', [
    {'platform': 'youtube', 'revision': 1},
    {'platform': 'youtube', 'revision': 'x', 'cookies': ''},
    {},
])
def test_an_incomplete_reply_is_no_login(data):
    assert site_logins.StoredLogin.from_json(data) is None


def test_the_hint_only_speaks_to_login_failures():
    run_ = site_logins.LoginRun('/tmp/x', _login())
    assert run_.hint(ResolveError('no video')) == ''
    assert 'refused' in run_.hint(ResolveError('Private video', kind='auth'))
    assert 'no login is stored' in site_logins.LoginRun().hint(
        ResolveError('Private video', kind='auth'))
