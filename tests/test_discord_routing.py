"""discord_bot/bot.py: what happens to a link with no directly ingestible
media behind it.

Every such link goes to the in-process yt-dlp resolver, logged in with the
site login the index stores for it (bots_common/site_logins.py):

  * a link a real extractor claims is resolved straight away;
  * a link nothing claims may still hide a video only the generic extractor
    finds, so it is probed — public address, metadata only — before any
    download starts, and only a few per message;
  * the login is fetched before anything else, and an index that can't be
    asked is reported as itself rather than resolved logged out, which
    would turn a restart into a settled "login required" 🚫.

discord.py and aiohttp are faked in conftest, and yt-dlp is faked here;
nothing touches a gateway or a socket.
"""
import asyncio
import os
import stat
import time
import types

import pytest

from bots_common import resolver, site_logins, sniff
from bots_common.index_client import AuthError, IndexUnavailable
from discord_bot import bot as botmod

YOUTUBE = 'https://www.youtube.com/watch?v=1'
ARTICLE = 'https://news.example.com/article'

COOKIES = ('# Netscape HTTP Cookie File\n'
           '.youtube.com\tTRUE\t/\tTRUE\t0\tSAPISID\told\n')
ROTATED = ('# Netscape HTTP Cookie File\n'
           '# This file is generated by yt-dlp.  Do not edit.\n'
           '.youtube.com\tTRUE\t/\tTRUE\t0\tSAPISID\tnew\n')


def run(coro):
    return asyncio.run(coro)


class FakeMessage:
    def __init__(self):
        self.id = 200
        self.channel = types.SimpleNamespace(id=100)
        self.jump_url = 'https://discord.test/jump'


class FakeIndex:
    """The two site-login calls the link path makes."""

    def __init__(self, login=None, raises=None):
        self.login = login
        self.raises = raises
        self.cooldown = 0.0           # seconds the client still refuses
        self.asked = []
        self.stored = []

    def blocked(self):
        return self.cooldown

    async def site_login(self, url):
        self.asked.append(url)
        if self.raises is not None:
            raise self.raises
        return self.login

    async def store_site_login(self, login, text):
        self.stored.append((login.platform, login.revision, text))
        return login.revision + 1


def _login():
    return site_logins.StoredLogin('youtube', 'YouTube', 7, COOKIES)


@pytest.fixture
def bot(monkeypatch):
    """An IndexBot with only the collaborators the link path touches."""
    b = botmod.IndexBot.__new__(botmod.IndexBot)
    b.index = FakeIndex()
    b.reactions, b.removed, b.logs, b.ingested = [], [], [], []

    async def react(message, emoji):
        b.reactions.append(emoji)

    async def unreact(message, emoji):
        b.removed.append(emoji)

    async def log(text):
        b.logs.append(text)

    async def ingest(src, message, tags):
        b.ingested.append((src, list(tags)))
        return botmod._Outcome(botmod.OK)

    b._react, b._unreact, b._log, b._ingest = react, unreact, log, ingest
    monkeypatch.setattr(botmod.config, 'YTDLP_MAX_PROBES', 4)
    monkeypatch.setattr(botmod.config, 'YTDLP_MAX_DURATION', 60)
    monkeypatch.setattr(botmod.config, 'YTDLP_PROBE_TIMEOUT', 30)
    monkeypatch.setattr(botmod.config, 'YTDLP_QUALITY', '1080')
    monkeypatch.setattr(botmod.config, 'YTDLP_POT_PROVIDER', 'http://bgutil:4416')
    monkeypatch.setattr(botmod.config, 'YTDLP_COOKIES', '')
    monkeypatch.setattr(botmod.IndexBot, '_resolver_enabled',
                        staticmethod(lambda: True))
    monkeypatch.setattr(sniff, 'require_public', lambda url: None)
    return b


@pytest.fixture
def ytdlp(monkeypatch, tmp_path):
    """resolver.resolve / probe stand-ins. `resolve` writes a file and, when
    it was handed cookies, plays yt-dlp saving the rotated jar into them."""
    state = types.SimpleNamespace(calls=[], probes=[], error=None,
                                  probe_error=None, used_cookies=True,
                                  rotate=True, cookie_seen=None,
                                  cookie_mode=None,
                                  meta=resolver.Probe('Clip', 42))

    def resolve(url, tmpdir, max_bytes, cookies=None, stall_timeout=None,
                **kw):
        state.calls.append({'url': url, 'cookies': cookies, **kw})
        if cookies:
            with open(cookies, encoding='utf-8') as fh:
                state.cookie_seen = fh.read()
            state.cookie_mode = stat.S_IMODE(os.stat(cookies).st_mode)
            if state.rotate:
                with open(cookies, 'w', encoding='utf-8') as fh:
                    fh.write(ROTATED)
        if state.error is not None:
            raise state.error
        path = tmp_path / 'ytdlp-fake.mp4'
        path.write_bytes(b'x')
        return resolver.Resolved(str(path), 'Clip.mp4', 'youtube',
                                 state.used_cookies and bool(cookies))

    def probe(url, cookies=None, pot_provider=None):
        state.probes.append(url)
        if state.probe_error is not None:
            raise state.probe_error
        return state.meta

    monkeypatch.setattr(resolver, 'resolve', resolve)
    monkeypatch.setattr(resolver, 'probe', probe)
    monkeypatch.setattr(resolver, 'filter_resolvable',
                        lambda urls: [u for u in urls if 'youtube' in u])
    return state


# ── _plan_links: who gets probed ──────────────────────────────────────────
def test_a_claimed_link_is_resolved_without_a_probe(bot):
    assert bot._plan_links([YOUTUBE], {YOUTUBE}) == [(YOUTUBE, False)]


def test_an_unclaimed_link_is_probed_first(bot):
    assert bot._plan_links([ARTICLE], set()) == [(ARTICLE, True)]


def test_a_link_dump_cannot_become_a_probe_storm(bot, monkeypatch):
    monkeypatch.setattr(botmod.config, 'YTDLP_MAX_PROBES', 2)
    urls = [f'https://news.example.com/{n}' for n in range(6)]
    assert len(bot._plan_links(urls + [YOUTUBE], {YOUTUBE})) == 3


def test_probes_can_be_turned_off(bot, monkeypatch):
    monkeypatch.setattr(botmod.config, 'YTDLP_MAX_PROBES', 0)
    assert bot._plan_links([ARTICLE, YOUTUBE], {YOUTUBE}) == [
        (YOUTUBE, False)]


def test_a_repeated_link_is_planned_once(bot):
    assert bot._plan_links([YOUTUBE, YOUTUBE], {YOUTUBE}) == [
        (YOUTUBE, False)]


def test_nothing_to_try_returns_handled_false(bot, ytdlp, monkeypatch):
    """The contract _handle_message relies on to post its 🚫."""
    monkeypatch.setattr(botmod.config, 'YTDLP_MAX_PROBES', 0)
    handled, outcomes = run(bot._resolve_and_ingest(FakeMessage(), [ARTICLE],
                                                    []))
    assert handled is False and outcomes == []


def test_with_the_resolver_off_nothing_is_tried(bot, ytdlp, monkeypatch):
    monkeypatch.setattr(botmod.IndexBot, '_resolver_enabled',
                        staticmethod(lambda: False))
    handled, _ = run(bot._resolve_and_ingest(FakeMessage(), [YOUTUBE], []))
    assert handled is False
    assert ytdlp.calls == [] and bot.index.asked == []


# ── Logins ────────────────────────────────────────────────────────────────
def test_the_stored_login_reaches_yt_dlp_as_a_private_file(bot, ytdlp):
    bot.index.login = _login()

    outcome = run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert outcome.emoji == botmod.OK
    assert bot.index.asked == [YOUTUBE]
    assert ytdlp.cookie_seen == COOKIES
    assert ytdlp.cookie_mode == 0o600
    # Deleted afterwards — a cookies.txt is the account.
    assert not os.path.exists(ytdlp.calls[0]['cookies'])


def test_quality_and_po_tokens_are_passed_through(bot, ytdlp):
    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))
    assert ytdlp.calls[0]['quality'] == '1080'
    assert ytdlp.calls[0]['pot_provider'] == 'http://bgutil:4416'


def test_rotated_cookies_are_sent_back_after_a_download_that_used_them(
        bot, ytdlp):
    bot.index.login = _login()

    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert bot.index.stored == [('youtube', 7, ROTATED)]


def test_nothing_is_sent_back_when_the_login_was_not_what_worked(bot, ytdlp):
    """YouTube retried without the login: the jar from the failed first
    run says nothing good about the session."""
    bot.index.login = _login()
    ytdlp.used_cookies = False

    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert bot.index.stored == []


def test_nothing_is_sent_back_after_a_failure(bot, ytdlp):
    bot.index.login = _login()
    ytdlp.error = resolver.ResolveError("Private video", kind='auth')

    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert bot.index.stored == []


def test_an_unchanged_jar_is_not_sent_back(bot, ytdlp):
    bot.index.login = _login()
    ytdlp.rotate = False

    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert bot.index.stored == []


def test_without_a_stored_login_the_mounted_fallback_is_used(bot, ytdlp,
                                                             monkeypatch):
    monkeypatch.setattr(botmod.config, 'YTDLP_COOKIES', '/run/cookies.txt')
    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))
    assert ytdlp.calls[0]['cookies'] == '/run/cookies.txt'


def test_a_rejected_index_login_backs_off_and_resolves_nothing(bot, ytdlp):
    bot.index.raises = AuthError("rejected")

    outcome = run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert outcome.emoji == botmod.BACKOFF and outcome.retryable is True
    assert ytdlp.calls == []


def test_an_unreachable_index_is_not_resolved_logged_out(bot, ytdlp):
    """Resolving anyway would turn "the index was restarting" into a
    settled "login required" 🚫 for a link that has a login stored."""
    bot.index.raises = IndexUnavailable("the index is unreachable")

    outcome = run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert outcome.emoji == botmod.ERROR and outcome.retryable is True
    assert ytdlp.calls == []
    assert 'site login' in bot.logs[0]


def test_a_refused_stored_login_says_what_an_admin_can_do(bot, ytdlp):
    bot.index.login = _login()
    ytdlp.error = resolver.ResolveError(
        "Sign in to confirm you're not a bot", kind='auth')

    outcome = run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))

    assert outcome.emoji == botmod.UNSUPPORTED
    assert 'stored YouTube login was refused' in bot.logs[0]
    assert site_logins.ADMIN_PAGE in bot.logs[0]


def test_a_missing_login_says_one_can_be_added(bot, ytdlp):
    ytdlp.error = resolver.ResolveError("This video is private", kind='auth')
    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))
    assert 'no login is stored' in bot.logs[0]


def test_other_failures_carry_no_login_hint(bot, ytdlp):
    ytdlp.error = resolver.ResolveError("no downloadable video found")
    run(bot._resolve_one(YOUTUBE, False, FakeMessage(), []))
    assert 'login' not in bot.logs[0]


def test_the_site_tag_rides_along(bot, ytdlp):
    outcome = run(bot._resolve_one(YOUTUBE, False, FakeMessage(), ['cats']))
    src, tags = bot.ingested[0]
    assert tags == ['cats', 'youtube']
    assert src.filename == 'Clip.mp4'
    assert outcome.emoji == botmod.OK


# ── The probe, for links nothing claims ───────────────────────────────────
def test_a_page_with_a_video_is_probed_then_downloaded(bot, ytdlp):
    outcome = run(bot._resolve_one(ARTICLE, True, FakeMessage(), []))
    assert ytdlp.probes == [ARTICLE]
    assert [c['url'] for c in ytdlp.calls] == [ARTICLE]
    assert outcome.emoji == botmod.OK


def test_a_page_with_no_video_downloads_nothing(bot, ytdlp):
    ytdlp.meta = resolver.Probe('An article')
    outcome = run(bot._resolve_one(ARTICLE, True, FakeMessage(), []))
    assert outcome.emoji == botmod.UNSUPPORTED and outcome.retryable is False
    assert ytdlp.calls == []


def test_a_page_of_several_videos_is_refused(bot, ytdlp):
    ytdlp.meta = resolver.Probe('Mix', is_playlist=True, entry_count=40)
    outcome = run(bot._resolve_one(ARTICLE, True, FakeMessage(), []))
    assert outcome.emoji == botmod.UNSUPPORTED
    assert '40 videos' in outcome.reason
    assert ytdlp.calls == []


def test_a_private_address_is_never_probed(bot, ytdlp, monkeypatch):
    """The generic extractor reads whatever page it is pointed at, from
    inside the stack's networks."""
    def refuse(url):
        raise sniff.Blocked("intranet is not a public address")
    monkeypatch.setattr(sniff, 'require_public', refuse)

    outcome = run(bot._resolve_one('http://intranet/x', True, FakeMessage(),
                                   []))

    assert outcome.emoji == botmod.UNSUPPORTED
    assert ytdlp.probes == [] and ytdlp.calls == []


def test_an_unreadable_page_is_reported_verbatim(bot, ytdlp):
    ytdlp.probe_error = resolver.ResolveError(
        "Unsupported URL: https://news.example.com/article")
    outcome = run(bot._resolve_one(ARTICLE, True, FakeMessage(), []))
    assert outcome.emoji == botmod.UNSUPPORTED
    assert 'Unsupported URL' in bot.logs[0]


def test_a_probe_that_hangs_is_retryable(bot, ytdlp, monkeypatch):
    monkeypatch.setattr(botmod.config, 'YTDLP_PROBE_TIMEOUT', 0.01)

    def slow(url, cookies=None, pot_provider=None):
        time.sleep(0.2)
        return ytdlp.meta
    monkeypatch.setattr(resolver, 'probe', slow)

    outcome = run(bot._resolve_one(ARTICLE, True, FakeMessage(), []))

    assert outcome.emoji == botmod.ERROR and outcome.retryable is True
    assert ytdlp.calls == []


# ── The message-level wrapper ─────────────────────────────────────────────
def test_the_index_backoff_short_circuits_before_any_download(bot, ytdlp):
    bot.index.cooldown = 900

    handled, outcomes = run(bot._resolve_and_ingest(
        FakeMessage(), [YOUTUBE], []))

    assert handled is True
    assert [o.emoji for o in outcomes] == [botmod.BACKOFF]
    assert ytdlp.calls == [] and bot.index.asked == []


def test_every_planned_link_gets_its_own_outcome(bot, ytdlp):
    handled, outcomes = run(bot._resolve_and_ingest(
        FakeMessage(), [YOUTUBE, ARTICLE], []))
    assert handled is True
    assert [o.emoji for o in outcomes] == [botmod.OK, botmod.OK]
    assert ytdlp.probes == [ARTICLE]


def test_the_progress_marker_is_cleared_even_when_a_resolve_raises(bot,
                                                                   ytdlp):
    async def boom(url, probe, message, tags):
        raise RuntimeError("resolver exploded")

    bot._resolve_one = boom
    with pytest.raises(RuntimeError):
        run(bot._resolve_and_ingest(FakeMessage(), [YOUTUBE], []))
    assert botmod.DOWNLOADING in bot.reactions
    assert botmod.DOWNLOADING in bot.removed
