"""The store → thumbnail → encrypt → index pipeline.

Shared by the upload route and the staging-queue promote step. The caller
must deliver the file into Config.UPLOAD_FOLDER first (a temp name is fine)
so the rename to the final content-addressed name never crosses filesystem
boundaries; only the staging→UPLOAD_FOLDER hop may cross a Docker bind
mount, and that is the caller's shutil.move.
"""
import os
import shutil
from datetime import datetime

from ..auth.db import get_or_create_user_enc_key, get_user_enc_key
from ..config import Config
from ..notifications import build_media_event, publish_event
from .crypto import ENC_SUFFIX, decrypt_file, enc_name, encrypt_file, strip_enc
from .db import (
    get_media_privacy_state,
    get_privacy_for_file,
    hash_exists,
    insert_media,
    media_path,
    set_media_paths_privacy,
    thumb_path,
)
from .processing import (
    file_type,
    gen_image_thumb,
    gen_placeholder_thumb,
    sha256_file,
)
from .tagging import tag_list, tag_str
from .tasks import enqueue_video_thumb


def ingest_file(tmp_path, ext, tags, uid, is_private, premade_thumb=None,
                filehash=None):
    """Take ownership of `tmp_path` (already inside Config.UPLOAD_FOLDER) and
    index it as `<sha256>.<ext>`.

    `premade_thumb` is an already-rendered thumbnail to copy instead of
    generating one (the staging scanner pre-renders video thumbs, saving an
    ffmpeg pass and the placeholder round-trip).

    `filehash` is the SHA-256 of `tmp_path` when the caller computed it
    while writing the file (see processing.save_stream_hashed); otherwise it
    is computed here.

    Returns ('ok', filehash) or ('duplicate', filehash); `tmp_path` is
    removed on duplicate.
    """
    fh = filehash or sha256_file(tmp_path)
    if hash_exists(fh):
        os.remove(tmp_path)
        return 'duplicate', fh

    # Final names are decided up front, and a private upload never touches
    # the plaintext ones.
    #
    # A private upload is encrypted straight to the `.enc` names, never
    # written as `<hash>.<ext>` first and then deleted: that name is
    # content-addressed, so a *concurrent* public upload of the same bytes
    # may already own it and have a row pointing at it. Deleting it would
    # leave that row referencing a missing file — silent data loss, visible
    # only to the integrity scan. The same goes for `<hash>.png`, the
    # thumbnail. This way the two privacy variants never share a path.
    is_video = ext in Config.ALLOWED_VIDEO_EXT
    suffix = ENC_SUFFIX if is_private else ''
    final = os.path.join(Config.UPLOAD_FOLDER, f"{fh}.{ext}{suffix}")
    tpath = os.path.join(Config.THUMB_FOLDER, f"{fh}.png{suffix}")
    key = get_or_create_user_enc_key(uid) if is_private else None

    # The thumbnail is rendered from `tmp_path`, which is still plaintext,
    # before the media file is moved or encrypted. For a private upload it
    # is rendered into the non-served scratch dir and encrypted into place,
    # so no plaintext thumbnail is ever reachable under THUMB_FOLDER.
    plain_thumb = tpath if not is_private else os.path.join(
        Config.tmp_dir(), f"ingest-{fh}.png")
    has_real_thumb = False
    try:
        if premade_thumb and os.path.exists(premade_thumb):
            shutil.copyfile(premade_thumb, plain_thumb)
            has_real_thumb = True
        elif ext in Config.ALLOWED_IMAGE_EXT | Config.ALLOWED_GIF_EXT:
            gen_image_thumb(tmp_path, plain_thumb)
        else:
            # Video thumbs (ffmpeg) are generated by the background worker;
            # serve a placeholder until it finishes.
            gen_placeholder_thumb(plain_thumb)

        if is_private:
            encrypt_file(plain_thumb, tpath, key)
            encrypt_file(tmp_path, final, key)
            os.remove(tmp_path)
        else:
            os.rename(tmp_path, final)
            # The upload routes create tmp_path with tempfile, which makes it
            # 0600, and a rename keeps the mode. Without this, uploads would
            # be readable by root alone, unlike the 0644 of every file
            # written any other way, and host-side tooling running as the
            # owning user (backups, rsync) would silently skip them.
            os.chmod(final, 0o644)
    finally:
        if is_private and os.path.exists(plain_thumb):
            os.remove(plain_thumb)

    # The type (image/gif/video) is added as a tag unless the uploader
    # already typed it; tag search ignores case, so this check does too.
    tag_parts = tag_list(tags)
    ftype = file_type(f"f.{ext}")
    if ftype and ftype not in (t.lower() for t in tag_parts):
        tag_parts.append(ftype)
    full_tags = tag_str(tag_parts)
    if insert_media(final, tpath, full_tags, fh, uid, is_private):
        event = None
        if not is_private:
            event = build_media_event(final, tpath, fh, full_tags, uid,
                                      datetime.now().isoformat())
        if is_video and not has_real_thumb:
            # Defer the announcement until the real thumb exists so the
            # bot never posts the placeholder for a video.
            enqueue_video_thumb(final, tpath, key, notify_event=event)
        elif event:
            publish_event(event)
        return 'ok', fh
    # Lost the dedup race (another request inserted the same filehash
    # first) — remove what this request wrote, except files the winning
    # row itself references (same hash means the loser's paths usually
    # ARE the winner's files).
    for p in (final, tpath):
        if p and os.path.exists(p) and not get_privacy_for_file(os.path.basename(p)):
            os.remove(p)
    return 'duplicate', fh


def set_media_privacy(mid, private, user_id, is_admin=False):
    """Flip one media row between public and private, converting its file
    and thumbnail on disk. Encryption always uses the *owner's* key (also
    for admin flips), since serving decrypts with the owner's key.

    Returns True on success (a flip to the current state is a no-op
    success), False when the row is missing, not owned by `user_id`
    (unless admin), or the files could not be converted.
    """
    row = get_media_privacy_state(mid)
    if not row:
        return False
    fp, th, owner, is_priv = row
    if owner != user_id and not is_admin:
        return False
    if bool(is_priv) == bool(private):
        return True

    if private:
        key = get_or_create_user_enc_key(owner)
    else:
        key = get_user_enc_key(owner)
        if not key:
            return False

    def _new_name(name):
        if not name:
            return name
        return enc_name(name) if private else strip_enc(name)

    new_fp, new_th = _new_name(fp), _new_name(th)
    converted = []   # (src_abs, dst_abs) pairs actually written
    try:
        for name, new_name, resolve in ((fp, new_fp, media_path),
                                        (th, new_th, thumb_path)):
            if not name or new_name == name:
                continue
            src = resolve(name)
            # A missing file still gets its row flipped — it is equally
            # unservable under either name (integrity-check territory).
            if not os.path.exists(src):
                continue
            dst = resolve(new_name)
            if private:
                encrypt_file(src, dst, key)
            else:
                decrypt_file(src, dst, key)
            converted.append((src, dst))
    except Exception:
        for _, dst in converted:
            if os.path.exists(dst):
                os.remove(dst)
        return False

    # Point the row at the converted names first, then drop the old files —
    # a crash in between leaves stale extra files, never a broken row.
    if not set_media_paths_privacy(mid, new_fp, new_th, private):
        for _, dst in converted:
            if os.path.exists(dst):
                os.remove(dst)
        return False
    for src, _ in converted:
        if os.path.exists(src):
            os.remove(src)
    return True
