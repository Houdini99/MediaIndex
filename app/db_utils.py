"""Shared DB helpers for app.media.db and app.auth.db.

PostgreSQL only: one database (Config.DATABASE_URL), two schemas — `media` and `users` —
accessed through a per-process psycopg connection pool.
"""
import os
import threading
from contextlib import contextmanager
from datetime import datetime, timezone

from app.config import Config

# One ConnectionPool per worker process, created lazily on first use.
# Gunicorn forks before importing the app (no --preload), so module state
# is naturally per-process — but the pid guard makes sure a future
# --preload (or anything else that forks after import) can never share
# pooled sockets across processes.
_pool = None
_pool_pid = None
_pool_lock = threading.Lock()


def _get_pool():
    global _pool, _pool_pid
    pid = os.getpid()
    if _pool is None or _pool_pid != pid:
        with _pool_lock:
            if _pool is None or _pool_pid != pid:
                from psycopg_pool import ConnectionPool
                # max_size sized to the worst case per process: 4 request
                # threads × 2 nested connections (media + auth) + scanner
                # and thumb threads.
                _pool = ConnectionPool(
                    Config.DATABASE_URL, min_size=1, max_size=10, open=True
                )
                _pool_pid = pid
    return _pool


@contextmanager
def db_conn():
    """Yield a pooled connection that is always returned to the pool.

    The pool commits on clean exit and rolls back on exception, so no
    call site may leave an aborted transaction behind on a path that
    exits cleanly.
    """
    with _get_pool().connection() as conn:
        yield conn


def db_now():
    """Storage value for 'now': an aware UTC datetime (timestamptz)."""
    return datetime.now(timezone.utc)


# DDL — schemas `media` and `users`. Keep each table's column order when
# adding a column: several consumers index row tuples positionally.
_PG_DDL = """
CREATE SCHEMA IF NOT EXISTS media;
CREATE SCHEMA IF NOT EXISTS users;

CREATE TABLE IF NOT EXISTS users.users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             text        NOT NULL UNIQUE,
    password_hash        text        NOT NULL,
    enc_key              bytea,
    is_admin             boolean     NOT NULL DEFAULT false,
    dav_password_hash    text,
    dav_password_created timestamptz
);

-- Telegram ingest identity. Two columns because the website accepts
-- either form, but they are not equally trustworthy: `telegram_user_id`
-- is immutable and is the real identity, while a @username can be
-- released by its owner and re-registered by a stranger — who would then
-- inherit that user's ingest path. app.auth.db.resolve_telegram_user()
-- therefore matches on the id first and pins the id the first time a
-- username match succeeds, so an account is only ever username-matched
-- once.
--
-- The partial unique indexes are load-bearing rather than hygiene:
-- without them two index users can claim the same Telegram account and
-- ingest silently lands on whichever row the planner returns first.
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS telegram_user_id  bigint;
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS telegram_username text;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_telegram_id
    ON users.users (telegram_user_id) WHERE telegram_user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_telegram_username
    ON users.users (lower(telegram_username)) WHERE telegram_username IS NOT NULL;

-- Discord ingest identity: the numeric user id, set only through a link
-- code. /settings issues a one-time code, the user DMs it to the bot, and
-- the bot hands it back with the sender's id as Discord reports it — so a
-- link proves the same person controls both accounts, and nobody can claim
-- someone else's id by typing it. Codes are stored hashed, single use and
-- short-lived. Unique for the same reason as the Telegram columns.
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS discord_user_id bigint;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_discord_id
    ON users.users (discord_user_id) WHERE discord_user_id IS NOT NULL;
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS discord_link_code_hash text;
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS discord_link_expires timestamptz;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_discord_link_code
    ON users.users (discord_link_code_hash)
    WHERE discord_link_code_hash IS NOT NULL;

-- Session generation. Sessions are signed cookies holding only a user id,
-- so without this nothing server-side could end one: logging out cleared
-- the cookie in *that* browser, and a password change left every other
-- copy — including a stolen one — valid for as long as it kept being used.
-- Login stamps the current value into the session; the per-request user
-- load refuses a session whose stamp no longer matches; a password change
-- bumps it. A session from before this column existed carries no stamp and
-- counts as generation 0, so deploying it logs nobody out.
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS session_gen integer NOT NULL DEFAULT 0;

-- Set on accounts an admin creates, and when an admin resets someone
-- else's password: the admin chose that password and knows it. Until the
-- user picks their own, every page they open leads to /login/new-password. Existing accounts default to false, so deploying
-- this asks nobody for a new password.
ALTER TABLE users.users ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;

-- Site logins for the bots' yt-dlp (app/site_logins.py): one
-- Netscape cookies.txt per platform, AES-GCM-sealed under a key derived
-- from SECRET_KEY, so this table in a pg_dump opens nothing. `revision`
-- is drawn from one sequence on every write and is what a bot's
-- write-back of rotated cookies must match — a per-row counter would
-- restart at 1 after a delete, and a write-back from before the delete
-- could then land on the new upload.
CREATE SEQUENCE IF NOT EXISTS users.site_logins_revision;
CREATE TABLE IF NOT EXISTS users.site_logins (
    platform    text        PRIMARY KEY,
    cookies     bytea       NOT NULL,
    revision    bigint      NOT NULL,
    uploaded_by bigint      REFERENCES users.users(id) ON DELETE SET NULL,
    uploaded_at timestamptz NOT NULL,
    rotated_at  timestamptz
);

CREATE TABLE IF NOT EXISTS users.failed_logins (
    ip           text        PRIMARY KEY,
    count        integer     NOT NULL DEFAULT 0,
    banned       boolean     NOT NULL DEFAULT false,
    last_attempt timestamptz,
    manual       boolean     NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS media.media (
    id          bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filepath    text    NOT NULL,
    thumb       text,
    tags        text,
    filehash    text    UNIQUE,
    uploaded_by bigint  REFERENCES users.users(id),
    upload_date timestamptz,
    is_private  boolean NOT NULL DEFAULT false,
    ftype       text
);
CREATE INDEX IF NOT EXISTS idx_media_privacy
    ON media.media (is_private, uploaded_by);

-- Every /media/<name> and /thumbs/<name> request authorises itself with
-- `WHERE filepath = %s OR thumb = %s` (get_privacy_for_file), and a
-- gallery page makes 30 of those at once; the thumbnail worker's
-- compare-and-set matches on `thumb` too. Without these each one was a
-- sequential scan of the whole table.
CREATE INDEX IF NOT EXISTS idx_media_filepath ON media.media (filepath);
CREATE INDEX IF NOT EXISTS idx_media_thumb    ON media.media (thumb);

-- Media kind, stored rather than derived. Deriving it means OR-ing ten
-- `filepath ILIKE '%%.mp4'`-style patterns, which no index can serve, and
-- the gallery makes that call twice per page (the page query and its
-- COUNT). Leading-wildcard ILIKE would also do case-insensitive matching
-- on names that are lowercase hex by construction.
ALTER TABLE media.media ADD COLUMN IF NOT EXISTS ftype text;
CREATE INDEX IF NOT EXISTS idx_media_ftype ON media.media (ftype, id DESC);

CREATE TABLE IF NOT EXISTS media.staging (
    id            bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint  NOT NULL REFERENCES users.users(id) ON DELETE CASCADE,
    fname         text    NOT NULL,
    size          bigint,
    mtime         double precision,
    filehash      text,
    thumb         text,
    ftype         text,
    status        text    NOT NULL DEFAULT 'pending'
                  CHECK (status IN ('pending','ready','duplicate',
                                    'unsupported','error','promoting')),
    error         text,
    discovered_at timestamptz,
    claimed_at    timestamptz,
    UNIQUE (user_id, fname)
);
CREATE INDEX IF NOT EXISTS idx_staging_user
    ON media.staging (user_id, status);

-- ── Near-duplicate finder (admin panel) ──────────────────────────────────
-- One row per sampled frame: images/GIFs contribute a single frame_idx=0
-- row, videos one per sampled timestamp. The 64-bit perceptual hashes are
-- stored as *signed* bigints (Postgres has no unsigned type) — see the
-- to_signed/to_unsigned helpers in app.media.dupes_db.
CREATE TABLE IF NOT EXISTS media.media_hash (
    media_id  bigint  NOT NULL REFERENCES media.media(id) ON DELETE CASCADE,
    frame_idx integer NOT NULL DEFAULT 0,
    phash     bigint  NOT NULL,
    dhash     bigint  NOT NULL,
    ahash     bigint  NOT NULL,
    PRIMARY KEY (media_id, frame_idx)
);

-- Per-media bookkeeping for the hash index: which source the hashes were
-- computed from, the algorithm version, and the dimensions/size the
-- keeper heuristic and the "wasted bytes" figure are derived from. A row
-- with `error` set records a media file that could not be hashed, so the
-- scan does not retry it on every incremental run.
CREATE TABLE IF NOT EXISTS media.media_hash_meta (
    media_id  bigint PRIMARY KEY REFERENCES media.media(id) ON DELETE CASCADE,
    source    text        NOT NULL,
    algo_ver  integer     NOT NULL,
    frames    integer     NOT NULL,
    width     integer,
    height    integer,
    bytes     bigint,
    ftype     text,
    hashed_at timestamptz NOT NULL,
    error     text
);

-- Pairs an admin marked "not duplicates". Always stored with a_id < b_id.
CREATE TABLE IF NOT EXISTS media.dupe_dismissed (
    a_id         bigint NOT NULL REFERENCES media.media(id) ON DELETE CASCADE,
    b_id         bigint NOT NULL REFERENCES media.media(id) ON DELETE CASCADE,
    dismissed_by bigint REFERENCES users.users(id) ON DELETE SET NULL,
    dismissed_at timestamptz,
    PRIMARY KEY (a_id, b_id)
);

-- Step one of the two-step resolve: losers are quarantined (and tagged)
-- rather than deleted. `tags_backup` holds the exact pre-quarantine tag
-- string so a restore is byte-identical.
CREATE TABLE IF NOT EXISTS media.dupe_quarantine (
    media_id    bigint PRIMARY KEY REFERENCES media.media(id) ON DELETE CASCADE,
    keeper_id   bigint REFERENCES media.media(id) ON DELETE SET NULL,
    distance    integer,
    marked_by   bigint REFERENCES users.users(id) ON DELETE SET NULL,
    marked_at   timestamptz NOT NULL,
    tags_backup text
);

-- Scan-job state lives in the database, not in process memory: gunicorn
-- runs two workers and the progress poll may land on the one that is not
-- scanning.
CREATE TABLE IF NOT EXISTS media.dupe_job (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state            text NOT NULL CHECK (state IN ('running','done','error','cancelled')),
    params           text,
    total            integer NOT NULL DEFAULT 0,
    processed        integer NOT NULL DEFAULT 0,
    hashed           integer NOT NULL DEFAULT 0,
    skipped          integer NOT NULL DEFAULT 0,
    failed           integer NOT NULL DEFAULT 0,
    cancel_requested boolean NOT NULL DEFAULT false,
    error            text,
    started_by       bigint REFERENCES users.users(id) ON DELETE SET NULL,
    started_at       timestamptz,
    heartbeat        timestamptz,
    finished_at      timestamptz
);
-- At most one running job across all workers.
CREATE UNIQUE INDEX IF NOT EXISTS idx_dupe_job_one_running
    ON media.dupe_job ((state)) WHERE state = 'running';

-- The three "who did this" columns above were first created without an
-- ON DELETE action, so deleting any admin who had ever run a scan,
-- dismissed a pair or quarantined an item failed on the foreign key — and
-- it failed at the very end of admin remove_user(), after that user's media
-- and WebDAV inbox had already been deleted. They are audit fields, so the
-- row outlives its actor with a NULL (every reader LEFT JOINs users).
-- CREATE TABLE IF NOT EXISTS never revisits an existing table, so the
-- constraints on existing databases are rewritten here; the confdeltype
-- test makes it a no-op on every boot after the first.
DO $$
DECLARE r record;
BEGIN
    FOR r IN
        SELECT c.conrelid::regclass AS tbl, c.conname, a.attname AS col
        FROM pg_constraint c
        JOIN pg_attribute a
          ON a.attrelid = c.conrelid AND a.attnum = c.conkey[1]
        WHERE c.contype = 'f'
          AND c.confrelid = 'users.users'::regclass
          AND c.confdeltype <> 'n'
          AND ((c.conrelid = 'media.dupe_dismissed'::regclass AND a.attname = 'dismissed_by')
            OR (c.conrelid = 'media.dupe_quarantine'::regclass AND a.attname = 'marked_by')
            OR (c.conrelid = 'media.dupe_job'::regclass AND a.attname = 'started_by'))
    LOOP
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
        EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (%I) '
                       'REFERENCES users.users(id) ON DELETE SET NULL',
                       r.tbl, r.conname, r.col);
    END LOOP;
END $$;
"""

# Both gunicorn workers run the init DDL concurrently at boot; concurrent
# CREATE ... IF NOT EXISTS can race into a spurious pg_type duplicate-key
# error, so the DDL runs under a session advisory lock.
_PG_INIT_LOCK_KEY = 0x6D656469_61  # 'media' as hex, arbitrary constant
_pg_schema_ready = False


def ftype_backfill_sql():
    """UPDATE that fills `ftype` for rows predating the column.

    The extension lists come from Config so this cannot drift from
    `processing.file_type()` — the same mapping expressed in SQL, applied
    once. `WHERE ftype IS NULL` makes it a no-op on every boot after the
    first, and the `.enc` suffix is stripped first so a private file is
    classified by its real extension.
    """
    def _match(exts):
        alts = '|'.join(sorted(e.lower() for e in exts))
        return f"base ~ '\\.({alts})$'"

    return f"""
    UPDATE media.media SET ftype = CASE
        WHEN {_match(Config.ALLOWED_GIF_EXT)}   THEN 'gif'
        WHEN {_match(Config.ALLOWED_IMAGE_EXT)} THEN 'image'
        WHEN {_match(Config.ALLOWED_VIDEO_EXT)} THEN 'video'
        ELSE 'unknown' END
    FROM (SELECT id AS bid,
                 lower(regexp_replace(filepath, '\\.enc$', '')) AS base
          FROM media.media WHERE ftype IS NULL) AS src
    WHERE media.media.id = src.bid AND media.media.ftype IS NULL;
    """


def ensure_pg_schema():
    """Create schemas/tables/indexes idempotently.

    Called once per process by create_app (and by the pytest fixtures);
    later calls return straight away.
    """
    global _pg_schema_ready
    if _pg_schema_ready:
        return
    with db_conn() as conn:
        cur = conn.cursor()
        cur.execute("SELECT pg_advisory_lock(%s)", (_PG_INIT_LOCK_KEY,))
        try:
            cur.execute(_PG_DDL)
            # Runs inside the same advisory-locked section as the ALTER that
            # adds the column, so no worker can observe rows with a NULL
            # ftype and filter them out of the gallery.
            cur.execute(ftype_backfill_sql())
            conn.commit()
        finally:
            cur.execute("SELECT pg_advisory_unlock(%s)", (_PG_INIT_LOCK_KEY,))
            conn.commit()
    _pg_schema_ready = True


def like_escape(value):
    r"""Escape LIKE wildcards in user input for use with ESCAPE '\'."""
    return (
        str(value)
        .replace('\\', '\\\\')
        .replace('%', '\\%')
        .replace('_', '\\_')
    )
